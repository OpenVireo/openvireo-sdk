#!/bin/sh
# Builds the OPAQUE WASM module and writes it, base64-inlined, to ../vendor/opaque/opaque-wasm.js.
# Paths are remapped so the output doesn't depend on the checkout or the cargo home (reproducible with
# the toolchain pinned in rust-toolchain.toml and the committed Cargo.lock).
set -eu
cd "$(dirname "$0")"
CARGO_HOME=${CARGO_HOME:-$HOME/.cargo}
RUSTFLAGS="--remap-path-prefix=$PWD=/src --remap-path-prefix=$CARGO_HOME=/cargo" \
  cargo build --locked --release --target wasm32-unknown-unknown
wasm=target/wasm32-unknown-unknown/release/openvireo_opaque_wasm.wasm
out=../vendor/opaque/opaque-wasm.js
mkdir -p ../vendor/opaque
{
  echo "// Generated by opaque-wasm/build.sh from opaque-wasm/ (opaque-ke 4.0.1). Do not edit."
  echo "// SPDX-License-Identifier: MIT OR Apache-2.0"
  printf 'export default "%s";\n' "$(base64 < "$wasm" | tr -d '\n')"
} > "$out"
# Notices for every crate compiled into the module (MIT text for dual-licensed crates)
notices=../vendor/opaque/THIRD-PARTY-LICENSES.txt
{
  echo "Third-party code compiled into opaque-wasm.js (generated by opaque-wasm/build.sh)."
  cargo tree --locked --target wasm32-unknown-unknown -e normal,no-proc-macro --prefix none -f '{p}|{l}' \
    | grep -v '^openvireo-opaque-wasm' | sed 's/ (\*)$//' | sort -u | while IFS='|' read -r pkg lic; do
      dir=$(ls -d "$CARGO_HOME"/registry/src/*/"$(echo "$pkg" | sed 's/ v/-/')" | head -1)
      file=""
      for f in LICENSE-MIT LICENSE LICENSE-BSD LICENSE-APACHE; do [ -f "$dir/$f" ] && { file=$dir/$f; break; }; done
      [ -n "$file" ] || { echo "no licence file for $pkg" >&2; exit 1; }
      printf '\n================================================================================\n%s (%s)\n\n' "$pkg" "$lic"
      tr -d '\r' < "$file"
    done
} > "$notices"
echo "wasm  $(shasum -a 256 "$wasm" | cut -d' ' -f1)  $(wc -c < "$wasm" | tr -d ' ') bytes"
echo "js    $(shasum -a 256 "$out" | cut -d' ' -f1)"
